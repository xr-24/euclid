"""Write the asset catalog and credits for every placeable model in the project.

Runs under any Python 3:
    python scripts/assets/build_catalog.py

Reads world/assets/library/<licence>/<id>/asset.json (written by scripts/blender/build_library.py)
and the Poly Haven model report (world/assets/thirdparty/polyhaven/models/models.json), then writes
    world/assets/library/catalog.json  - what the game loads (AssetLibrary in world/scripts)
    world/assets/library/CREDITS.md    - attribution for every library model, grouped by licence
    world/assets/library/<licence>/README.md - what the licence of that folder allows
The catalog is generated: edit the sources (scripts/assets/*.json) and rebuild instead.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORLD = ROOT / 'world'
LIBRARY = WORLD / 'assets/library'
POLYHAVEN = WORLD / 'assets/thirdparty/polyhaven/models'

# What each licence folder allows, in plain words, for the per-folder README and the credits.
LICENCES = {
    'cc0': ('CC0 1.0 (public domain)', 'https://creativecommons.org/publicdomain/zero/1.0/',
            'No conditions. Credit is appreciated but not required.'),
    'cc-by': ('CC BY 4.0', 'https://creativecommons.org/licenses/by/4.0/',
              'Any use, including commercial and open-source distribution, as long as the author is credited, '
              'the licence is linked and changes are indicated.'),
    'cc-by-sa': ('CC BY-SA 4.0', 'https://creativecommons.org/licenses/by-sa/4.0/',
                 'Any use with credit; modified versions of these models must be shared under the same licence.'),
    'cc-by-nc': ('CC BY-NC 4.0', 'https://creativecommons.org/licenses/by-nc/4.0/',
                 'NON-COMMERCIAL ONLY. Fine while Construct is free and not monetised. Remove this folder '
                 'before selling Construct, monetising it, or publishing it under an open-source licence.'),
    'cc-by-nc-sa': ('CC BY-NC-SA 4.0', 'https://creativecommons.org/licenses/by-nc-sa/4.0/',
                    'NON-COMMERCIAL ONLY, and modified versions of these models must stay under CC BY-NC-SA. '
                    'Remove this folder before selling Construct, monetising it, or publishing it under an '
                    'open-source licence.'),
}

# Poly Haven models, by catalog category. Anything unlisted is a 'prop'.
POLYHAVEN_CATEGORIES = {
    'tree': ['tree_small_02', 'island_tree_01', 'island_tree_02', 'island_tree_03', 'jacaranda_tree'],
    'plant': ['potted_plant_01', 'potted_plant_02', 'shrub_01', 'shrub_03', 'shrub_sorrel_01', 'searsia_lucida', 'grass_bermuda_01'],
    'rock': ['coast_rocks_05', 'sand_rocks_small_01', 'coast_land_rocks_03'],
    'furniture': ['round_wooden_table_01', 'outdoor_table_chair_set_01'],
    'bust': ['marble_bust_01'],
    'statue': ['horse_statue_01', 'lion_head'],
    'structure': ['modular_wooden_pier'],
    'floating': ['wine_barrel_01', 'wooden_crate_01', 'ocean_buoy'],
}


def library_assets() -> dict:
    assets = {}
    for path in sorted(LIBRARY.glob('*/*/asset.json')):
        asset = json.loads(path.read_text(encoding='utf-8'))
        group = path.parent.parent.name
        assets[asset['id']] = {
            'title': asset['title'],
            'category': asset['category'],
            'tags': asset.get('tags', []),
            'scene': f'res://{path.parent.relative_to(WORLD).as_posix()}/{asset["id"]}.glb',
            'size_m': asset['size_m'],
            'triangles': asset['triangles'],
            'licence': group,
            'source': asset['source'],
        }
    return assets


def polyhaven_assets() -> dict:
    report_path = POLYHAVEN / 'models.json'
    report = json.loads(report_path.read_text(encoding='utf-8')) if report_path.exists() else {}
    category = {i: c for c, ids in POLYHAVEN_CATEGORIES.items() for i in ids}
    assets = {}
    for asset_id, info in sorted(report.items()):
        if not (POLYHAVEN / f'{asset_id}.glb').exists():
            continue
        x, y, z = info['size_m']
        assets[asset_id] = {
            'title': asset_id.replace('_', ' ').capitalize(),
            'category': category.get(asset_id, 'prop'),
            'tags': [],
            'scene': f'res://assets/thirdparty/polyhaven/models/{asset_id}.glb',
            'size_m': {'width': x, 'depth': y, 'height': z},
            'triangles': info['triangles'],
            'licence': 'cc0',
            'source': {'site': 'Poly Haven', 'page': f'https://polyhaven.com/a/{asset_id}', 'author': 'Poly Haven',
                       'licence': 'cc0', 'licence_label': LICENCES['cc0'][0], 'licence_url': LICENCES['cc0'][1]},
        }
    return assets


def write_credits(assets: dict):
    lines = ['# Asset library credits', '',
             'Generated by scripts/assets/build_catalog.py from each model\'s asset.json. Models are grouped by '
             'licence; each licence folder\'s README.md says what it allows. Poly Haven models (CC0) are credited '
             'in world/assets/thirdparty/polyhaven/CREDITS.md.', '']
    for group, (label, url, rule) in LICENCES.items():
        entries = [(i, a) for i, a in assets.items() if a['licence'] == group and a['source']['site'] != 'Poly Haven']
        if not entries:
            continue
        lines += [f'## {label}', '', rule, '']
        for asset_id, a in sorted(entries, key=lambda e: e[1]['title']):
            s = a['source']
            author = f'[{s["author"]}]({s["author_page"]})' if s.get('author_page') else s['author']
            lines.append(f'- **{s.get("title") or a["title"]}** by {author}, [{s["site"]}]({s["page"]}), '
                         f'licensed under [{s["licence_label"] or label}]({s["licence_url"] or url}). '
                         f'{s.get("changes", "")} Library id `{asset_id}`.')
        lines.append('')
    (LIBRARY / 'CREDITS.md').write_text('\n'.join(lines), encoding='utf-8')


def write_folder_notes(assets: dict):
    for group, (label, url, rule) in LICENCES.items():
        folder = LIBRARY / group
        if folder.is_dir():
            ids = sorted(i for i, a in assets.items() if a['licence'] == group and a['source']['site'] != 'Poly Haven')
            text = [f'# {label}', '', rule, '', f'Licence text: {url}', '',
                    'Models in this folder (authors and sources in ../CREDITS.md):', ''] + [f'- `{i}`' for i in ids]
            (folder / 'README.md').write_text('\n'.join(text) + '\n', encoding='utf-8')


def main():
    LIBRARY.mkdir(parents=True, exist_ok=True)
    assets = {**polyhaven_assets(), **library_assets()}
    catalog = {'schema_version': 1, 'generated_by': 'scripts/assets/build_catalog.py', 'assets': assets}
    (LIBRARY / 'catalog.json').write_text(json.dumps(catalog, indent=1, ensure_ascii=False, sort_keys=True), encoding='utf-8')
    write_credits(assets)
    write_folder_notes(assets)
    counts = {}
    for a in assets.values():
        counts[a['licence']] = counts.get(a['licence'], 0) + 1
    print(f'CONSTRUCT_CATALOG {len(assets)} assets {counts}', flush=True)


if __name__ == '__main__':
    main()
